def _user(handle: str | None) -> dict[str, Any] | None:
    if handle is None:
        return None
    account_id, display_name = USERS[handle]
    return {"accountId": account_id, "displayName": display_name, "active": True}


def build_issues() -> dict[str, Any]:
    issues: list[dict[str, Any]] = []
    for n, summary, issue_type, status, assignee, priority, created, updated, due, intent in SPECS:
        issues.append(
            {
                "id": str(10000 + n),
                "key": f"DEMO-{n}",
                "_intent": intent,  # documentation only; the normaliser ignores it
                "fields": {
                    "summary": summary,
                    "issuetype": {"name": issue_type},
                    "project": {"key": "DEMO", "name": "Demo Delivery"},
                    "status": {
                        "name": status,
                        "statusCategory": {"key": CATEGORY[status], "name": status},
                    },
                    "assignee": _user(assignee),
                    "priority": {"name": priority} if priority else None,
                    "created": created,
                    "updated": updated,
                    "duedate": due,
                    "resolution": {"name": "Done"} if status == "Done" else None,
                    "resolutiondate": "@-10d" if status == "Done" else None,
                },
            }
        )
    return {"issues": issues}


def build_changelogs() -> dict[str, Any]:
    """Mirror the shape of POST /rest/api/3/changelog/bulkfetch.

    The live response keys histories by ``issueId``; ``issueKey`` is included here so
    fixtures stay readable. The Phase 7 client maps id to key before handing the
    result to the engine.
    """
    entries: list[dict[str, Any]] = []
    for n, changes in sorted(CHANGELOGS.items()):
        entries.append(
            {
                "issueId": str(10000 + n),
                "issueKey": f"DEMO-{n}",
                "changeHistories": [
                    {
                        "id": str(900000 + n * 100 + i),
                        "created": f"@-{days}d",
                        "items": [
                            {
                                "field": "status",
                                "fieldId": "status",
                                "fieldtype": "jira",
                                "fromString": frm,
                                "toString": to,
                            }
                        ],
                    }
                    for i, (days, frm, to) in enumerate(changes)
                ],
            }
        )
    return {"issueChangeLogs": entries}


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, payload in (
        ("demo_issues.json", build_issues()),
        ("demo_changelogs.json", build_changelogs()),
    ):
        path = OUT_DIR / name
        path.write_text(json.dumps(payload, indent=2, sort_keys=False) + "\n", encoding="utf-8")
        print(f"wrote {path.relative_to(OUT_DIR.parents[2])}")
    print(f"{len(SPECS)} issues, {len(CHANGELOGS)} changelog records")


if __name__ == "__main__":
    main()
